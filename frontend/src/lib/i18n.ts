const dicts: Record<LangId, Dict> = { en, es, fr, ru, it, pt };

const STORE_KEY = "kisassistant_lang";

function detectLang(): LangId {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (
      saved === "en" ||
      saved === "es" ||
      saved === "fr" ||
      saved === "ru" ||
      saved === "it" ||
      saved === "pt"
    ) {
      return saved;
    }
  } catch {
    // storage unavailable — fall through to browser detection
  }
  const nav = (navigator.language || "en").toLowerCase().split("-")[0];
  if (
    nav === "es" ||
    nav === "fr" ||
    nav === "ru" ||
    nav === "it" ||
    nav === "pt"
  )
    return nav;
  return "en";
}

let current: LangId = detectLang();
if (typeof document !== "undefined") document.documentElement.lang = current;

const listeners = new Set<() => void>();

export function getLang(): LangId {
  return current;
}

/** Persist the language (per browser) and re-render every subscriber. */
export function setLang(lang: LangId): void {
  if (current === lang) return;
  current = lang;
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch {
    // ignore
  }
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  listeners.forEach((fn) => fn());
}

/** Global translate function: t("login.welcome"), t("chat.greet", { name }). */
export function t(
  key: StringKey,
  vars?: Record<string, string | number>,
): string {
  let s: string = dicts[current][key] ?? dicts.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars))
      s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Reactive hook — components using translated strings must call it so they re-render on language switch. */
export function useT(): { t: typeof t; lang: LangId } {
  useSyncExternalStore(
    (fn) => {
      listeners.add(fn);
      return () => {
        listeners.delete(fn);
      };
    },
    () => current,
  );
  return { t, lang: current };
}
